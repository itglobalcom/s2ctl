"""Сколько ждать завершения задачи платформы: дефолт и таймаут текущего вызова CLI."""
from contextvars import ContextVar
from typing import Optional

# Замеры на проде (проект 547560, локация 7, платформа без нагрузки): пересборка
# VMware-сервера — 296 с, заказ сервера — 213 и 186 с, копия сервера — 134 с, создание
# маршрутизируемой сети — 59 с, удаление сервера — 26–36 с, заказ шлюза — 24 с, его
# питание — 20–25 с, питание сервера, запись DNS и создание изолированной сети — 6–13 с.
# Дефолт берётся с запасом к самой долгой замеренной операции (296 с × 1,6 ≈ 474,
# округлено до 480): он обязан покрывать пересборку сервера под нагрузкой платформы,
# но не превращать зависшую задачу в бесконечно висящую команду. Операции, которых
# замеры не покрывают (сервер с большим диском), — случай `--timeout`.
DEFAULT_TASK_TIMEOUT = 480

# Таймаут задаёт опция команды, а нужен он в глубине ожидания задачи — в базовом
# сервисе, до которого значение пришлось бы тащить параметром через каждую операцию
# каждого раздела. Поэтому оно живёт в контексте вызова и читается в момент
# ожидания — `asyncio.run` копирует контекст и видит его.
TASK_TIMEOUT_SECS: ContextVar[Optional[int]] = ContextVar('task_timeout_secs', default=None)


def task_timeout_secs() -> int:
    """Таймаут ожидания задачи: значение `--timeout` текущего вызова, иначе дефолт."""
    return TASK_TIMEOUT_SECS.get() or DEFAULT_TASK_TIMEOUT
