"""Сколько ждать завершения задачи платформы: дефолт и таймаут текущего вызова CLI."""
from contextvars import ContextVar
from typing import Optional

# Замеры на проде: заказ VMware-сервера — 186 с, удаление сервера — 26 с, питание,
# запись DNS и сети — 6–13 с. Дефолт берётся с запасом к самой долгой замеренной
# операции (186 с × 1,6): он обязан покрывать заказ сервера под нагрузкой платформы,
# но не превращать зависшую задачу в бесконечно висящую команду. Операции, которых
# замеры не покрывают (копия и пересборка сервера с большим диском), — случай `--timeout`.
DEFAULT_TASK_TIMEOUT = 300

# Таймаут задаёт опция команды, а сервис к этому моменту уже создан колбэком группы
# click: группа выполняется до разбора параметров своей команды, и передать значение
# в конструктор сервиса нечем. Поэтому оно живёт в контексте вызова и читается
# в момент ожидания — `asyncio.run` копирует контекст и видит его.
TASK_TIMEOUT_SECS: ContextVar[Optional[int]] = ContextVar('task_timeout_secs', default=None)


def task_timeout_secs() -> int:
    """Таймаут ожидания задачи: значение `--timeout` текущего вызова, иначе дефолт."""
    return TASK_TIMEOUT_SECS.get() or DEFAULT_TASK_TIMEOUT
